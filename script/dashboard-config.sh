#!/usr/bin/env bash
# Write dashboard/config.js from the deployment files (public addresses only).
#   FROM_BLOCK = the guard's creation block on Lasna (found by the receipt verifier's search)
set -euo pipefail
cd "$(dirname "$0")/.."
set -a; source deployments/testnet.env; source deployments/wallets.env; set +a
L=https://lasna-rpc.rnk.dev/
if [[ -z "${FROM_BLOCK:-}" ]]; then # binary search for the guard's creation block (pruned history = absent)
  hi=$(cast block-number --rpc-url $L); lo=$((hi - 500000)); (( lo < 0 )) && lo=0
  while (( lo < hi )); do mid=$(( (lo + hi) / 2 ))
    c=$(cast code $PM --rpc-url $L -B $mid 2>/dev/null || echo 0x); [[ "$c" != "0x" ]] && hi=$mid || lo=$((mid + 1)); done
  FROM_BLOCK=$lo
fi
# Only the chains this deployment has a vault on (the default setup skips Unichain).
chain() { # chain <id> <name> <rpc> <usdc> <explorer tx url>
  local v r; v=$(eval echo "\${VAULT_$1:-}"); r=$(eval echo "\${REGISTRY_$1:-}"); [[ -n "$v" ]] || return 0
  echo "    { id: $1, name: \"$2\", rpc: \"$3\", vault: \"$v\", registry: \"$r\", usdc: \"$4\", tx: \"$5\" },"
}
CHAIN_ROWS=$(
  chain 84532 "Base Sepolia" https://sepolia.base.org 0x036CbD53842c5426634e7929541eC2318f3dCF7e https://sepolia.basescan.org/tx/
  chain 1301 "Unichain Sepolia" https://sepolia.unichain.org 0x31d0220469e10c4E71834a79b1f276d740d3768F https://sepolia.uniscan.xyz/tx/
  chain 11155111 "Ethereum Sepolia" https://ethereum-sepolia-rpc.publicnode.com 0x1c7D4B196Cb0C7B01d743Fbc6116a902379C7238 https://sepolia.etherscan.io/tx/
)
cat > dashboard/config.js.tmp <<EOF
// Generated by script/dashboard-config.sh. Public addresses only.
window.PM_CONFIG = {
  lasna: "https://lasna-rpc.rnk.dev/",
  explorer: "https://lasna.reactscan.net",
  guard: "$PM",
  fromBlock: $FROM_BLOCK,
  agent: "$AGENT",
  agentName: "${AGENT_NAME:-Andy}",
  liveStart: "${LIVE_START:-2026-11-23}",
  payees: {
    "$SELLER": "the BTC report (x402 shop)",
    "${SELLER2:-0x2}": "the BTC report (second x402 shop)",
    "$OWNER": "the owner",
    "${SUI_SHOP:-0x}": "the shop on Sui",
    "${SOL_SHOP_ID:-0x}": "the shop on Solana",
    // retired keys (rotated out): approved when these payments were made
    "${SELLER_OLD:-0x3}": "the BTC report (x402 shop)",
    "${SELLER2_OLD:-0x4}": "the BTC report (second x402 shop)",
    "${SUI_SHOP_OLD:-0x5}": "the shop on Sui",
    "${SOL_SHOP_ID_OLD:-0x6}": "the shop on Solana"
  },
  chains: [
$CHAIN_ROWS
  ]
};
EOF
mv dashboard/config.js.tmp dashboard/config.js # written whole or not at all
echo "wrote dashboard/config.js (fromBlock $FROM_BLOCK)"
